import {
  claimAutomationRun,
  createWorkspaceFileForUser,
  getWorkspaceComputer,
  listEnabledAutomationsForScheduler,
  updateAutomationRun,
  updateAutomationScheduleState,
} from "./db";

const MAX_AUTOMATIONS_PER_TICK = 25;
const ERROR_LIMIT = 1000;

export type WorkspaceBriefingInput = {
  workspace: { name: string };
  folders: Array<{ name: string }>;
  files: Array<{ name: string; mimeType: string; updatedAt: Date }>;
  chats: Array<{ title: string; updatedAt: Date }>;
  settings: { workspaceRules?: string | null };
};

function safeError(error: unknown) {
  const value = error instanceof Error ? error.message : "Nova could not complete this automation run.";
  return value.replace(/(?:api[_-]?key|token|secret)\s*=\s*\S+/gi, "[private value]").slice(0, ERROR_LIMIT);
}

function utcDateKey(date: Date) {
  return date.toISOString().slice(0, 10);
}

function shortList(values: string[], limit = 6) {
  if (!values.length) return "- None yet";
  return values.slice(0, limit).map(value => `- ${value}`).join("\n");
}

/** Creates a stable per-automation run key so duplicate cron delivery cannot create duplicate artifacts. */
export function getAutomationRunKey(kind: "workspace_digest", now: Date) {
  return `${kind}:${utcDateKey(now)}`;
}

/** Produces an account-private, deterministic briefing without exporting workspace content or using third-party services. */
export function buildWorkspaceBriefing(input: WorkspaceBriefingInput, now: Date) {
  const recentFiles = [...input.files]
    .sort((left, right) => new Date(right.updatedAt).getTime() - new Date(left.updatedAt).getTime())
    .map(file => `${file.name} (${file.mimeType})`);
  const recentChats = [...input.chats]
    .sort((left, right) => new Date(right.updatedAt).getTime() - new Date(left.updatedAt).getTime())
    .map(chat => chat.title);
  const rules = input.settings.workspaceRules?.trim();

  return [
    "# Daily workspace briefing",
    "",
    `Generated by Nova on ${now.toISOString()}. This report remains inside ${input.workspace.name}.`,
    "",
    "## Snapshot",
    "",
    `- ${input.folders.length} folder${input.folders.length === 1 ? "" : "s"}`,
    `- ${input.files.length} file${input.files.length === 1 ? "" : "s"}`,
    `- ${input.chats.length} saved conversation${input.chats.length === 1 ? "" : "s"}`,
    "",
    "## Recently updated files",
    "",
    shortList(recentFiles),
    "",
    "## Recent conversations",
    "",
    shortList(recentChats),
    ...(rules ? ["", "## Workspace rules", "", rules] : []),
    "",
  ].join("\n");
}

export async function runDueAutomations(now = new Date(), limit = MAX_AUTOMATIONS_PER_TICK) {
  const scheduled = await listEnabledAutomationsForScheduler(Math.max(1, Math.min(limit, MAX_AUTOMATIONS_PER_TICK)));
  const outcome = { processed: 0, succeeded: 0, failed: 0, skipped: 0 };

  for (const { automation, ownerId } of scheduled) {
    const runKey = getAutomationRunKey(automation.kind, now);
    const run = await claimAutomationRun({ automationId: automation.id, workspaceId: automation.workspaceId, runKey });
    if (!run) {
      outcome.skipped += 1;
      continue;
    }

    outcome.processed += 1;
    try {
      const computer = await getWorkspaceComputer(ownerId);
      const artifact = await createWorkspaceFileForUser(ownerId, {
        name: `daily-workspace-briefing-${utcDateKey(now)}.md`,
        content: buildWorkspaceBriefing(computer, now),
        mimeType: "text/markdown",
      });
      if (!artifact) throw new Error("Nova could not save the daily workspace briefing.");

      const summary = "Saved a private daily workspace briefing.";
      await updateAutomationRun({
        automationId: automation.id,
        workspaceId: automation.workspaceId,
        runId: run.id,
        status: "succeeded",
        summary,
        artifactFileId: artifact.id,
        completedAt: now,
      });
      await updateAutomationScheduleState({ automationId: automation.id, workspaceId: automation.workspaceId, lastRunAt: now, lastError: null });
      outcome.succeeded += 1;
    } catch (error) {
      const message = safeError(error);
      await updateAutomationRun({
        automationId: automation.id,
        workspaceId: automation.workspaceId,
        runId: run.id,
        status: "failed",
        errorMessage: message,
        completedAt: now,
      });
      await updateAutomationScheduleState({ automationId: automation.id, workspaceId: automation.workspaceId, lastError: message });
      outcome.failed += 1;
    }
  }

  return outcome;
}

export function isAuthorizedAutomationCron(authorization: string | undefined) {
  const secret = process.env.CRON_SECRET?.trim();
  return Boolean(secret && authorization === `Bearer ${secret}`);
}
